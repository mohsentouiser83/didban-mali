def create_styled_sheet(
    workbook: openpyxl.Workbook,
    title: str,
    headers: list[str],
    rows: list[list[Any]],
    header_color: str = "1E3A8A",
    zebra: bool = True,
):
    sheet = workbook.create_sheet(title=title)
    sheet.views.sheetView[0].rightToLeft = True

    header_font = Font(name="Vazirmatn", size=11, bold=True, color="FFFFFF")
    header_fill = PatternFill(start_color=header_color, end_color=header_color, fill_type="solid")
    regular_font = Font(name="Vazirmatn", size=10)
    alt_fill = PatternFill(start_color="F8FAFC", end_color="F8FAFC", fill_type="solid")
    
    thin_border = Border(
        left=Side(style="thin", color="CBD5E1"),
        right=Side(style="thin", color="CBD5E1"),
        top=Side(style="thin", color="CBD5E1"),
        bottom=Side(style="thin", color="CBD5E1"),
    )

    sheet.append(headers)
    for col_idx in range(1, len(headers) + 1):
        cell = sheet.cell(row=1, column=col_idx)
        cell.font = header_font
        cell.fill = header_fill
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = thin_border
    sheet.row_dimensions[1].height = 28

    for row_idx, row_data in enumerate(rows, start=2):
        sheet.append(row_data)
        sheet.row_dimensions[row_idx].height = 22
        is_even = row_idx % 2 == 0
        for col_idx, val in enumerate(row_data, start=1):
            cell = sheet.cell(row=row_idx, column=col_idx)
            cell.font = regular_font
            cell.border = thin_border
            if zebra and is_even:
                cell.fill = alt_fill

            if isinstance(val, (int, float)):
                cell.number_format = "#,##0"
                cell.alignment = Alignment(horizontal="left", vertical="center")
            else:
                cell.alignment = Alignment(horizontal="right", vertical="center")

    for col in sheet.columns:
        max_len = 0
        col_letter = get_column_letter(col[0].column)
        for cell in col:
            val_str = str(cell.value or "")
            max_len = max(max_len, len(val_str))
        sheet.column_dimensions[col_letter].width = max(max_len + 4, 14)


def write_csv(path: Path, headers: list[str], rows: list[list[Any]]):
    with path.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(headers)
        writer.writerows(rows)


