#!/usr/bin/env python3
"""Generate reviewable schema/OpenAPI snapshots from fresh executable source."""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "apps/api"))

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable
from didban.api import app
from didban.db import SCHEMA_LOCK, SCHEMA_TABLE_DDL, SCHEMA_VERSION, postgres_security_statements
from didban.models import Base

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    dialect = postgresql.dialect()
    statements = [
        "-- Generated by scripts/generate_contracts.py; fresh schema, no legacy migration.",
        "-- Use the limited application owner role. Do not run as a bypass-RLS application role.",
        "BEGIN;", f"SELECT pg_advisory_xact_lock({SCHEMA_LOCK});",
        SCHEMA_TABLE_DDL + ";",
        f"INSERT INTO didban_schema_version (id, version) VALUES (1, {SCHEMA_VERSION}) ON CONFLICT (id) DO NOTHING;",
    ]
    for table in Base.metadata.sorted_tables:
        statements.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ";")
        statements.extend(str(CreateIndex(index).compile(dialect=dialect)).strip() + ";" for index in sorted(table.indexes, key=lambda item: item.name or ""))
    statements.extend(statement + ";" for statement in postgres_security_statements())
    statements.append("COMMIT;")
    (ROOT / "database").mkdir(exist_ok=True)
    (ROOT / "contracts").mkdir(exist_ok=True)
    schema = "\n".join(line.rstrip() for line in "\n\n".join(statements).splitlines())
    (ROOT / "database/schema.sql").write_text(schema + "\n")
    (ROOT / "contracts/openapi.json").write_text(json.dumps(app.openapi(), ensure_ascii=False, indent=2, sort_keys=True) + "\n")
    print(f"Generated {len(Base.metadata.tables)} tables and {len(app.openapi()['paths'])} HTTP paths")


if __name__ == "__main__":
    main()
